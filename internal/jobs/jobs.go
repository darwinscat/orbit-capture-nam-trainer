// Package jobs holds the daemon's domain types: job kinds, lanes, states, the
// closed vocabularies of the shared schema (0001_init.sql: job_kind, job_state,
// job_error), and the Job row. It depends on nothing else
// in the tree so the store and the worker share one definition of a Job.
package jobs

import "time"

// Kinds (the job_kind domain). train_more continues a succeeded train from the
// weights the take already has, which is where every run of it continues from.
const (
	KindTrain     = "train"
	KindTrainMore = "train_more"
	KindProbeSelf = "probe_self"
)

// Lanes (jobs.lane, generated by the schema): train and train_more share the
// GPU-bound train lane; probe_self drains in its own lane alongside it.
const (
	LaneTrain = "train"
	LaneProbe = "probe"
)

// States (the job_state domain).
const (
	StateQueued    = "queued"
	StateRunning   = "running"
	StateSucceeded = "succeeded"
	StateFailed    = "failed"
	StateCancelled = "cancelled"
)

// Verdicts for probe_self (jobs.verdict).
const (
	VerdictPass = "pass"
	VerdictFail = "fail"
)

// Error codes — the job_error domain, a CLOSED list the app branches on. Nothing
// outside this list may ever be written to jobs.error_code.
const (
	ErrTrainFailed     = "train_failed"
	ErrResumeFailed    = "resume_failed"
	ErrStalled         = "stalled"
	ErrNoVerdict       = "no_verdict"
	ErrStopFailed      = "stop_failed"
	ErrScratch         = "scratch"
	ErrSpawn           = "spawn"
	ErrMaterialize     = "materialize"
	ErrWavInvalid      = "wav_invalid"
	ErrTakeGone        = "take_gone"
	ErrSignalMismatch  = "signal_mismatch"
	ErrBaseUnavailable = "base_unavailable"
	ErrCancelled       = "cancelled"
)

// (A stop had four states of its own here, and a live request three ways to fail. Both vocabularies
// are gone with the conversations that used them: a stop is heard at a checkpoint write, so there is
// no step between asking and acting to name, and listening is a read of the take's row rather than
// something a trainer answers. See migration 0007.)

// ProbeSelfEpochs is the fixed epoch count of a probe_self (the schema CHECKs it).
const ProbeSelfEpochs = 1

// Lane reports the scheduling lane a kind drains in — the same rule as the
// schema's generated jobs.lane column.
func Lane(kind string) string {
	if kind == KindProbeSelf {
		return LaneProbe
	}
	return LaneTrain
}

// LaneKinds returns every kind that drains in lane.
func LaneKinds(lane string) []string {
	if lane == LaneProbe {
		return []string{KindProbeSelf}
	}
	return []string{KindTrain, KindTrainMore}
}

// ValidKind reports whether k is one of the known job kinds.
func ValidKind(k string) bool {
	switch k {
	case KindTrain, KindTrainMore, KindProbeSelf:
		return true
	}
	return false
}

// IsTerminal reports whether a state is final (no further transitions).
func IsTerminal(state string) bool {
	return state == StateSucceeded || state == StateFailed || state == StateCancelled
}

// StoresModel reports whether a kind produces a .nam (a job_result row). Probes never do.
func StoresModel(kind string) bool { return kind == KindTrain || kind == KindTrainMore }

// Job is a row of the shared jobs table as the daemon reads it. Nullable columns
// are pointers. The request block (take_id … queued_at) is the app's and is frozen
// once the row is claimed; the run block is what this daemon writes.
type Job struct {
	ID int64

	// ---- the app writes (the request) ----
	TakeID             int64   // 0 = the take was wiped; the journal row survives, the claim skips it
	TakeLabel          string
	Kind               string
	Lane               string
	Epochs             int // total target (train_more: the TOTAL, not the delta)
	Arch               string
	Priority           string // high | normal | low
	Latency            *int64 // latency_samples; NULL ⇒ the trainer auto-detects
	WavSHA             string // = take_audio.sha256: the bytes the job pins
	RequiredNamVersion string
	BaseJobID          *int64 // train_more: provenance (the weights are the take's own)
	StartEpoch         *int64 // train_more: where this run's numbering begins (app-written)
	StopRequestedAt    *time.Time
	PausedAt           *time.Time
	CancelRequestedAt  *time.Time
	QueuedAt           time.Time

	// ---- the daemon writes (the run) ----
	State          string
	Worker         *string
	WorkerInstance *string
	ClaimToken     string // uuid text; "" until claimed. EVERY later write is fenced on it.
	PGID           *int
	ClaimedAt      *time.Time
	StartedAt      *time.Time
	FinishedAt     *time.Time
	Epoch          *int64 // progress: last finished epoch (absolute)
	Reached        *int64 // epochs the weights HAVE at the end
	SPerEpoch      *float64
	ESR            *float64
	Verdict        *string
	ErrorCode      *string
	ErrorMessage   *string
	NamVersion     *string
	DriverSHA256   *string
	SignalSHA256   *string
}
